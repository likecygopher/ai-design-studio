export function translate(locale: Locale, key: MessageKey | string, params?: MessageParams): string {
  const template =
    locale === "en"
      ? (messages.en as Record<string, string>)[key] ?? enByZh[key] ?? String(key)
      : (messages.zh as Record<string, string>)[key] ?? String(key);
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, token: string) =>
    token in params ? String(params[token]) : match
  );
}

export function hasMessage(locale: Locale, key: string): boolean {
  return Object.prototype.hasOwnProperty.call(messages[locale], key);
}
