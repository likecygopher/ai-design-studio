#!/usr/bin/env bash
# One-command production-like Docker deployment:
#   generate .env.docker (if missing) -> build -> migrate -> seed admin -> start
#   -> wait for /api/health and /api/ready -> print URL + admin credentials.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if ! command -v docker >/dev/null 2>&1; then
  echo "未安装 docker，请先安装 Docker Desktop / Docker Engine。" >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "缺少 docker compose v2 插件。" >&2
  exit 1
fi

ENV_FILE=".env.docker"
WEB_PORT="${WEB_PORT:-3000}"
POSTGRES_PORT="${POSTGRES_PORT:-5433}"

if [ ! -f "${ENV_FILE}" ]; then
  echo "==> 生成 ${ENV_FILE}"
  ADMIN_EMAIL="${ADMIN_EMAIL:-admin@example.com}"
  if [ -n "${ADMIN_PASSWORD:-}" ]; then
    ADMIN_PASS="$ADMIN_PASSWORD"
  else
    # 16+ chars with letters and digits (seed requires both).
    ADMIN_PASS="$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-18)Aa1"
  fi
  if ! [[ "$ADMIN_PASS" =~ ^[A-Za-z0-9._@-]{12,}$ ]]; then
    echo "ADMIN_PASSWORD 需 >=12 位且仅包含字母/数字/._@-" >&2
    exit 1
  fi
  AUTH_SECRET_VALUE="$(openssl rand -base64 48 | tr -d '\n')"
  umask 077
  cat > "${ENV_FILE}" <<EOF
# Generated by scripts/deploy-docker.sh — keep this file secret (chmod 600).
AUTH_SECRET=$AUTH_SECRET_VALUE
SEED_ADMIN_EMAIL=$ADMIN_EMAIL
SEED_ADMIN_PASSWORD=$ADMIN_PASS
WEB_PORT=$WEB_PORT
POSTGRES_PORT=$POSTGRES_PORT
APP_URL=${APP_URL:-http://localhost:$WEB_PORT}
# Optional: SSO / S3 / Redis / alerting — see .env.example
EOF
  echo "    管理员: $ADMIN_EMAIL"
  echo "    密码:   $ADMIN_PASS"
  echo "    （已保存到 ${ENV_FILE}，请妥善保管）"
else
  echo "==> 复用已有 ${ENV_FILE}"
fi

# shellcheck disable=SC1090
set -a; . "./${ENV_FILE}"; set +a

if [ "${DEPLOY_DRY_RUN:-0}" = "1" ]; then
  docker compose --env-file "${ENV_FILE}" --profile seed config >/dev/null
  echo "==> 干跑校验通过（DEPLOY_DRY_RUN=1，未构建/启动）"
  exit 0
fi

echo "==> 构建并启动 postgres / migrate / web / worker"
docker compose --env-file "${ENV_FILE}" up -d --build

if [ "${SKIP_SEED:-0}" != "1" ]; then
  echo "==> 初始化管理员（幂等；重复执行会重置该账号密码）"
  docker compose --env-file "${ENV_FILE}" --profile seed build seed
  docker compose --env-file "${ENV_FILE}" --profile seed run --rm seed
else
  echo "==> 跳过 seed（SKIP_SEED=1）"
fi

echo -n "==> 等待 Web 健康检查"
HEALTH_URL="http://127.0.0.1:${WEB_PORT}/api/health"
READY_URL="http://127.0.0.1:${WEB_PORT}/api/ready"
for _ in $(seq 1 60); do
  if curl -fsS "$HEALTH_URL" >/dev/null 2>&1; then
    echo " ok"
    break
  fi
  echo -n "."
  sleep 2
done

if ! curl -fsS "$HEALTH_URL" >/dev/null 2>&1; then
  echo
  echo "健康检查失败，查看日志：" >&2
  docker compose --env-file "${ENV_FILE}" logs --tail=80 web worker migrate
  exit 1
fi

if curl -fsS "$READY_URL" >/dev/null 2>&1; then
  echo "==> /api/ready: ok"
else
  echo "==> 警告：/api/ready 尚未就绪（worker 可能仍在启动）" >&2
fi

echo
echo "部署完成：http://localhost:${WEB_PORT}"
echo "管理员：${SEED_ADMIN_EMAIL}"
echo "密码：  ${SEED_ADMIN_PASSWORD}"
echo
echo "查看状态：docker compose --env-file ${ENV_FILE} ps"
echo "查看日志：docker compose --env-file ${ENV_FILE} logs -f web worker"
echo "停止：    docker compose --env-file ${ENV_FILE} down"
